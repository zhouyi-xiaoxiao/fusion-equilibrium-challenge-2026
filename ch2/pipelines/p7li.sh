# MAST pipeline profile "p7li" = INV_P7li_k50 (mast_public_test.npz md5 2d61b873…; variant "C4F" of development).
# The p7a inverse (theta = dr, lcp, b1, b2; FF' family "fe") with two additions:
#   * an l_i datum: a ridge model trained on DIII-D labels predicts the cylinder-equivalent internal inductance l_i,c of every frame
#     from dimensionless plasma-current ramp history (in resistive-time units) and two Thomson profile exponents; it enters the
#     Levenberg-Marquardt objective as ONE Gaussian pseudo-observation of the solution's l_i,c (sd = 0.5 x the cross-validated residual
#     sd x a support-distance inflation), and the static prior on b1 is relaxed (variance x 9) so that the datum replaces its mean;
#   * fallback validity gate ("F1"): a closed-form fallback solution is shipped only if it passes the inverse's own validity test.
# q95 / beta_N constants re-derived on this pipeline's own DIII-D maps (ch2/constants/p7li). The l_i model is
# ch2/constants/p7li/li_model_v3.json (regenerate: PIPE=p7li bash ch2/calibrate_d3d.sh <diii_d_train> <name> lifit).
