# the l_i model (DIII-D TRAIN labels only): feature tables of the 2,637 shots of splits/d3d_li_train.txt (16 frames each, clean +
# stressed pseudo-horizontal Thomson) and of the 330 check shots of splits/d3d_li_check.txt (all frames), target = l_i,c of the label
# map (cylinder-equivalent, li_core.li_cyl), quadratic ridge with shot-grouped 5-fold CV -> li_model_v3.json. Both lists are DIII-D
# train shots outside the 150-shot holdout and outside every other evaluation / calibration list of the development.
# The table builder writes shots in the completion order of its worker pool; the fit sums over rows in table order, so the shot order
# of the development tables (splits/d3d_li_{train,check}_roworder.txt, permutations of the two lists) is restored before the fit
# (ch2/reorder_table.py). Without that step the coefficients differ from the shipped ones at the 1e-9 relative level.
calib_lifit() {  # <diii_d_train dir> <out dir> <holdout spec>
  local D=$1 O=$2/lifit; mkdir -p "$O"
  ( cd "$SOLVER_DIR" && {
      $PY li_table.py --machine d3d --data-dir "$D" --files "$FEC_REPO/splits/d3d_li_train.txt" --wall "$GEOM/d3d_limiter_mask.npz" \
          --out "$O/table_d3d_train_v3.parquet" --frames-per-shot 16 --procs "$NPROC" 2>&1 | tail -1 | cut -c1-600 &
      $PY li_table.py --machine d3d --data-dir "$D" --files "$FEC_REPO/splits/d3d_li_check.txt" --wall "$GEOM/d3d_limiter_mask.npz" \
          --out "$O/table_d3d_check_v3.parquet" --frames-per-shot 0 --procs "$NPROC" 2>&1 | tail -1 | cut -c1-600 &
      wait
      for t in train check; do $PYS "$FEC_REPO/ch2/reorder_table.py" "$O/table_d3d_${t}_v3.parquet" "$FEC_REPO/splits/d3d_li_${t}_roworder.txt" | cut -c1-200; done
      $PY li_fit.py --quad --name li_model_v3 --target gt_lic --train "$O/table_d3d_train_v3.parquet" --check "$O/table_d3d_check_v3.parquet" \
          --out "$O/li_model_v3.json" --report "$O/li_model_v3_report.json" 2>&1 | grep -E "LIFIT|Error|Traceback" | cut -c1-600; } )
  [ -s "$O/li_model_v3.json" ] || { echo "LIFIT_FAILED: no model"; return 1; }
  $PYS - "$O/li_model_v3.json" "$FEC_REPO/ch2/constants/p7li/li_model_v3.json" <<'PY'
import json, sys
a, b = json.load(open(sys.argv[1])), json.load(open(sys.argv[2]))
a.pop("train_table", None); b.pop("train_table", None)           # provenance string (a path), not used by the model
print(f"COMPARE li_model_v3 (all fields but train_table) {'IDENTICAL' if a == b else 'DIFFERENT'}")
if a != b:
    for k in sorted(set(a) | set(b)):
        if a.get(k) != b.get(k): print("  differs:", k)
PY
}
